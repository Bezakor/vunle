/**
 * Scans the asset folders under public/ and writes what it finds to
 * src/lib/floatingManifest.ts and src/lib/brandManifest.ts.
 *
 * The point is that the folder is the interface: drop in whatever mix of images
 * and video you have, named however you like, and the tiles pick them up. No
 * per-file entry to write, and no need to match a filename the code expects.
 *
 * Runs automatically before `dev` and `build`, so a deploy after uploading new
 * files regenerates this without anyone remembering to.
 */
import fs from 'node:fs';
import path from 'node:path';

const DIR = path.join(process.cwd(), 'public', 'floating');
const OUT = path.join(process.cwd(), 'src', 'lib', 'floatingManifest.ts');
const BRAND_DIR = path.join(process.cwd(), 'public', 'brand');
const BRAND_OUT = path.join(process.cwd(), 'src', 'lib', 'brandManifest.ts');

const VIDEO = new Set(['.webm', '.mp4', '.mov', '.m4v', '.ogv']);
const IMAGE = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif']);

const files = fs.existsSync(DIR)
  ? fs
      .readdirSync(DIR)
      .filter((f) => {
        const ext = path.extname(f).toLowerCase();
        return VIDEO.has(ext) || IMAGE.has(ext);
      })
      // Natural sort, so asset-2 comes before asset-10 rather than after it.
      .sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }))
  : [];

const entries = files.map((file) => {
  const kind = VIDEO.has(path.extname(file).toLowerCase()) ? 'video' : 'image';
  // encodeURI so spaces and other awkward characters in a filename still
  // resolve as a URL.
  return `  { src: '/floating/${encodeURI(file)}', kind: '${kind}' },`;
});

const body = entries.length ? `\n${entries.join('\n')}\n` : '';

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-floating-manifest.mjs — do not edit by hand.
// Add or remove files in public/floating and this is rewritten on the next
// \`npm run dev\` or \`npm run build\`.
export type FloatingMedia = { src: string; kind: 'image' | 'video' };

export const FLOATING_MEDIA: FloatingMedia[] = [${body}];
`,
);

console.log(
  `floating manifest: ${files.length} file${files.length === 1 ? '' : 's'}` +
    (files.length ? ` — ${files.join(', ')}` : ' (none yet, tiles stay on their gradients)'),
);

// --- the logo ---------------------------------------------------------------
// Whatever is called logo.* in public/brand, so the file can be an svg, a png
// or a webp without anyone editing code to match. Nothing there yet just means
// the wordmark is drawn as text.
const logo = fs.existsSync(BRAND_DIR)
  ? fs
      .readdirSync(BRAND_DIR)
      .filter((f) => /^logo\.(svg|png|webp|avif|jpg|jpeg|gif)$/i.test(f))
      // Prefer a vector, then the order above.
      .sort((a, b) => (path.extname(a).toLowerCase() === '.svg' ? -1 : 0) -
                      (path.extname(b).toLowerCase() === '.svg' ? -1 : 0))[0]
  : undefined;

fs.writeFileSync(
  BRAND_OUT,
  `// Generated by scripts/generate-asset-manifest.mjs — do not edit by hand.
// Drop a file called logo.svg (or .png, .webp) into public/brand and this is
// rewritten on the next \`npm run dev\` or \`npm run build\`.
export const LOGO_SRC: string | null = ${logo ? `'/brand/${encodeURI(logo)}'` : 'null'};
`,
);

console.log(`brand manifest: ${logo ? logo : 'no logo yet, the wordmark is drawn as text'}`);
